#!/usr/bin/env node
/* Deutschweg — Goethe B1 word-list matcher (PRODUCTION: «مطابقة B1»).
 *
 * What it answers: how much of the official Goethe-Zertifikat B1 Wortliste does
 * the app's B1 band actually carry, and which entries does it miss?
 *
 * The official list is a copyrighted Goethe-Institut publication and is NOT
 * committed to this repository (same decision as A1 and A2). This tool reads a
 * plain one-headword-per-line transcription from outside the repo — built from
 * the DWDS index of the same list (https://www.dwds.de/lemma/wortschatz-goethe-
 * zertifikat/B1), which is the list's machine-readable twin: every entry it
 * carries IS on the list, so it can only be incomplete, never off-list.
 *
 *     GOETHE_B1_LIST=/path/to/b1_headwords.txt node tools/match-goethe-b1.js
 *
 * Two measures, both printed so neither can hide the other:
 *   headword — the entry is one of the authored words of an A0..B1 word list
 *   material — the entry appears anywhere in the A0..B1 lessons or reading texts
 *
 * B1 builds on A1 and A2, so the measured band is the cumulative one (A0+B1);
 * the B1-only band is printed beside it for information.
 *
 * Writes tools/goethe-b1-gap.txt (the recorded gap) when --write-gap is passed,
 * and exits non-zero when coverage falls under the floor kept in this file.
 *
 * A derived run (no transcription in the sandbox) reads the baseline from the
 * gap file's own header and is refused under --require-transcription. It is exact
 * for the corpus: the gap file is the open set and the corpus only grows, so it
 * may also rewrite the gap (--write-gap) — the header then carries the new baseline.
 */
const fs = require('fs');
const path = require('path');
const { loadCorpus, buildBands, makeClassify } = require('./goethe-match');

const root = path.resolve(__dirname, '..');
const LIST = process.env.GOETHE_B1_LIST || path.resolve(root, '..', 'goethe', 'b1_headwords.txt');
const GAP = path.join(root, 'tools', 'goethe-b1-gap.txt');
const PROMOTED = path.join(root, 'tools', 'goethe-b1-promoted.txt');
const WRITE_GAP = process.argv.includes('--write-gap');
const REQUIRE = process.argv.includes('--require-transcription');

/* Floors are the measured values of the last accepted run. They may only rise.
   Ratcheted after unit 8 (amendment B1-L4) named 240 more of the pool:
   raw 1326/1820 = 0.7286 and 1555/1820 = 0.8544, rounded down. */
const FLOOR = { headword: 0.728, material: 0.854 };

const HAVE_LIST = fs.existsSync(LIST);
if (!HAVE_LIST && REQUIRE) {
  console.error('no transcription at ' + LIST + ' and --require-transcription was passed');
  process.exit(2);
}

const win = loadCorpus(root);
const { bands, materialText } = buildBands(win, { b1: ['B1'], cumulative: ['A0', 'A1', 'A2', 'B1'] });
const classifyC = makeClassify(bands.cumulative, materialText);
const classifyB1 = makeClassify(bands.b1, materialText);

function readPromoted() {
  if (!fs.existsSync(PROMOTED)) return [];
  return fs.readFileSync(PROMOTED, 'utf8').split('\n')
    .filter(l => /^list\s+/.test(l)).map(l => l.replace(/^list\s+/, '').trim()).filter(Boolean);
}
function verifyPromoted(list) {
  const ok = [], bad = [];
  list.forEach(e => {
    const c = classifyC(e);
    (c.inHead && c.met ? ok : bad).push(e);
  });
  return { ok, bad };
}
function baselineFrom(text, fallback) {
  const m = /^#\s*baseline:\s*(\d+)\s+total,\s*(\d+)\s+authored,\s*(\d+)\s+met\s*$/mi.exec(text);
  if (!m) return fallback;
  return { total: +m[1], authored: +m[2], met: +m[3] };
}
function gapLines(rows) {
  const head = '# Recorded gap: Goethe B1 entries the app does not carry yet.\n' +
    '# Generated by tools/match-goethe-b1.js --write-gap.\n' +
    '# Two measures: authored headword (in an A0..B1 word list) and material (met in a lesson or reading text).\n' +
    '# Entries below are the ones no word list names yet; those marked "met" the learner already\n' +
    '# meets in the material and are the promotion pool (tools/goethe-b1-candidates.txt).\n' +
    '# baseline: ' + rows.length + ' total, ' + rows.filter(r => r.inHead).length + ' authored, ' +
    rows.filter(r => r.met).length + ' met\n\n';
  return head + rows.filter(r => !r.inHead).map(r => (r.met ? 'met ' : 'new ') + r.entry).join('\n') + '\n';
}

function classifyAll(entries) {
  return entries.map(e => Object.assign({ entry: e }, classifyC(e)));
}

function pct(v) { return Math.round(v * 100) + '%'; }

function run(entries, derived) {
  const rows = classifyAll(entries);
  const listed = rows.filter(r => r.inHead).length;
  const metCount = rows.filter(r => r.met).length;
  const promoted = verifyPromoted(readPromoted());
  if (promoted.ok.length) {
    console.log('  promoted file        ' + promoted.ok.length + ' entries verified as authored and met');
  }
  promoted.bad.forEach(e => console.log('  NOT verified (dropped): ' + e));
  const headRatio = listed / rows.length, metRatio = metCount / rows.length;

  console.log('\nGoethe B1 match — ' + (derived ? 'DERIVED run (no transcription in this sandbox)' : 'FULL run'));
  console.log('  source: ' + (derived ? 'tools/goethe-b1-gap.txt + its recorded baseline' : LIST));
  if (derived) {
    console.log('  exact for this corpus: the gap file is the set the last run missed and the corpus only grows.');
    console.log('  the full run returns as soon as a transcription is present (GOETHE_B1_LIST).');
  }
  console.log('  alphabetical list      ' + listed + '/' + rows.length + ' as headword · ' +
    metCount + '/' + rows.length + ' met · ' + (rows.length - listed) + ' still open');

  let failed = 0;
  function gate(name, value, floor) {
    const ok = value >= floor;
    console.log('  ' + (ok ? '✓' : '✗') + ' ' + name + ': ' + pct(value) + ' (floor ' + pct(floor) + ')');
    if (!ok) failed++;
  }
  console.log('\ncoverage gate  (floor = last accepted run · a ratchet, never lowered)');
  if (process.env.SHOW_RAW) {
    console.log('  raw ' + JSON.stringify({ headRatio: +headRatio.toFixed(4), metRatio: +metRatio.toFixed(4) }));
  }
  gate('main list as headword', headRatio, FLOOR.headword);
  gate('main list met in material', metRatio, FLOOR.material);

  if (WRITE_GAP) {
    fs.writeFileSync(GAP, gapLines(rows));
    console.log('\nwrote ' + path.relative(root, GAP) + ' (' + rows.filter(r => !r.inHead).length + ' entries open, ' +
      rows.filter(r => r.met && !r.inHead).length + ' of them met already)');
  }
  return failed;
}

if (HAVE_LIST) {
  const entries = fs.readFileSync(LIST, 'utf8').split('\n')
    .map(l => l.replace(/^#.*$/, '').trim()).filter(Boolean);
  const derived = process.argv.includes('--derived');
  process.exit(run(entries, derived));
}

const gapText = fs.readFileSync(GAP, 'utf8');
const base = baselineFrom(gapText, null);
if (!base) {
  console.error('no transcription and no baseline in ' + path.relative(root, GAP));
  process.exit(2);
}
/* A derived run: the baseline says how many entries existed and how many were
   carried; the open ones are listed in the gap file itself, so re-classifying
   exactly those lines reproduces the numbers without the transcription. */
const openLines = gapText.split('\n').filter(l => /^(met|new)\s+/.test(l));
const openEntries = openLines.map(l => ({ wasMet: l.startsWith('met '), entry: l.replace(/^(met|new)\s+/, '') }));
if (openEntries.length !== base.total - base.authored) {
  console.error('gap file holds ' + openEntries.length + ' open entries but its baseline implies ' +
    (base.total - base.authored));
  process.exit(2);
}
/* authored grows by the open entries the corpus now names; met starts from the
   baseline (the gap's own "met" lines are already inside base.met) and grows by
   entries that were neither named nor met before and are met now. */
const newlyAuthored = openEntries.filter(o => classifyC(o.entry).inHead).length;
const newlyMet = openEntries.filter(o => !o.wasMet && classifyC(o.entry).met).length;
const listed = base.authored + newlyAuthored;
const total = base.total;
const metCount = base.met + newlyMet;
const headRatio = listed / total, metRatio = metCount / total;

console.log('\nGoethe B1 match — DERIVED run (no transcription in this sandbox)');
console.log('  source: tools/goethe-b1-gap.txt + its recorded baseline');
console.log('  exact for this corpus: the gap file is the set the last run missed and the corpus only grows.');
console.log('  the full run returns as soon as a transcription is present (GOETHE_B1_LIST).');
const promoted = verifyPromoted(readPromoted());
if (promoted.ok.length) console.log('  promoted file        ' + promoted.ok.length + ' entries verified as authored and met');
promoted.bad.forEach(e => console.log('  NOT verified (dropped): ' + e));
console.log('  alphabetical list      ' + listed + '/' + total + ' as headword · ' + metCount + '/' + total + ' met · ' +
  (total - listed) + ' still open');
console.log('  corpus gained from the gap: ' + newlyAuthored + ' named, ' + newlyMet + ' newly met');
let failed = 0;
function gate(name, value, floor) {
  const ok = value >= floor;
  console.log('  ' + (ok ? '✓' : '✗') + ' ' + name + ': ' + pct(value) + ' (floor ' + pct(floor) + ')');
  if (!ok) failed++;
}
console.log('\ncoverage gate  (floor = last accepted run · a ratchet, never lowered)');
if (process.env.SHOW_RAW) {
  console.log('  raw ' + JSON.stringify({ headRatio: +headRatio.toFixed(4), metRatio: +metRatio.toFixed(4) }));
}
gate('main list as headword', headRatio, FLOOR.headword);
gate('main list met in material', metRatio, FLOOR.material);
if (WRITE_GAP) {
  /* A derived run may rewrite the gap, because the gap file IS the open set: every
     entry it lists is re-classified above, and no entry that is already carried can
     fall back (the corpus only grows). The header records the new baseline, so the
     next derived run starts from it. The transcript run writes the same file from
     the whole list whenever a transcription is present. */
  const stillOpen = openEntries.filter(o => !classifyC(o.entry).inHead)
    .map(o => (classifyC(o.entry).met ? 'met ' : 'new ') + o.entry);
  const head = '# Recorded gap: Goethe B1 entries the app does not carry yet.\n' +
    '# Generated by tools/match-goethe-b1.js --write-gap (DERIVED run: no transcription in the sandbox;\n' +
    '# the file itself is the open set, so re-classifying it reproduces the baseline exactly).\n' +
    '# baseline: ' + total + ' total, ' + listed + ' authored, ' + metCount + ' met\n\n';
  fs.writeFileSync(GAP, head + stillOpen.join('\n') + '\n');
  console.log('\nwrote ' + path.relative(root, GAP) + ' (' + stillOpen.length + ' entries open, ' +
    stillOpen.filter(l => l.startsWith('met ')).length + ' of them met already)');
}
process.exit(failed);
