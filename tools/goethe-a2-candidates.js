#!/usr/bin/env node
/* Deutschweg — the A2 harvest: entries the learner MEETS in material and no word
 * list names. These are the entries that hold the combined measure (list +
 * word groups as headwords) under its goal, and they are the pool a promotion
 * may draw from.
 *
 * Where the pool comes from: the official Goethe A2 list is copyrighted and its
 * transcription lives outside the repository, so a machine-readable index of the
 * same list (DWDS) is used to enumerate the entries. The DWDS index is the list
 * intersected with the DWDS dictionary: every entry it carries IS on the list, so
 * a promotion taken from it can never add an entry the list does not have — the
 * index can only be incomplete, never wrong in that direction. The partial
 * harvest (letters A–N) is recorded in the file header.
 *
 * Every line is verified against the corpus, not trusted:
 *   authored  — the entry is an item of some A0/A1/A2 word list  → drop
 *   met       — the learner meets it in a lesson, a step or a reading text → keep
 * Anything neither met nor authored is printed and dropped: the measure can only
 * move on entries the corpus really carries.
 *
 *     GOETHE_A2_HARVEST=/path/to/harvest.txt node tools/goethe-a2-candidates.js [--write]
 */
const fs = require('fs');
const path = require('path');
const { loadCorpus, buildBands, makeClassify } = require('./goethe-match');

const root = path.resolve(__dirname, '..');
const HARVEST = process.env.GOETHE_A2_HARVEST || '/home/user/goethe/a2_harvest_an.txt';
const OUT = path.join(root, 'tools', 'goethe-a2-candidates.txt');
const WRITE = process.argv.includes('--write');

if (!fs.existsSync(HARVEST)) {
  console.error('missing harvest file: ' + HARVEST);
  console.error('It is kept outside the repository (the list is copyrighted). See the tool header.');
  process.exit(2);
}
const win = loadCorpus(root);
const { bands, materialText } = buildBands(win, { cumulative: ['A0', 'A1', 'A2'] });
const classify = makeClassify(bands.cumulative, materialText);

const lines = fs.readFileSync(HARVEST, 'utf8').split('\n')
  .map(l => l.replace(/^#.*$/, '').trim()).filter(Boolean);

const authored = [], candidates = [], neither = [];
lines.forEach(entry => {
  const c = classify(entry);
  if (c.inHead) authored.push(entry);
  else if (c.met) candidates.push(entry);
  else neither.push(entry);
});

console.log('\nGoethe A2 harvest (verified against the corpus, not trusted)');
console.log('  lines read            ' + lines.length);
console.log('  already authored      ' + authored.length + '  → dropped');
console.log('  MET, NOT AUTHORED     ' + candidates.length + '  → the promotion pool');
console.log('  neither met nor named ' + neither.length + '  → dropped (the corpus does not carry them)');
if (authored.length) console.log('  authored: ' + authored.join(' · '));
if (neither.length) console.log('  not carried: ' + neither.join(' · '));

if (WRITE) {
  const head = '# Candidate pool: Goethe A2 entries the learner MET in material and no word list names.\n' +
    '# Generated by tools/goethe-a2-candidates.js from the partial harvest (letters A–N of the DWDS\n' +
    '# index of the same list, kept outside the repository because the list is copyrighted).\n' +
    '# Every line was verified against the corpus: authored lines and lines the corpus does not\n' +
    '# carry are excluded. Promoting an entry means naming it in a word list; the matcher then\n' +
    '# verifies authored AND met before the entry counts, so this file can never overstate.\n' +
    '# What is left to enumerate: letters O–Z of the list.\n';
  fs.writeFileSync(OUT, head + candidates.join('\n') + '\n');
  console.log('  wrote ' + path.relative(root, OUT) + ' (' + candidates.length + ' candidates)');
}
process.exit(0);
