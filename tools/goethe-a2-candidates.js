#!/usr/bin/env node
/* Deutschweg — the A2 harvest: entries the learner MEETS in material and no word
 * list names. These are the entries that hold the combined measure (list +
 * word groups as headwords) under its goal, and they are the pool a promotion
 * may draw from.
 *
 * Where the pool comes from: the official Goethe A2 list is copyrighted and its
 * transcription lives outside the repository, so a machine-readable index of the
 * same list (DWDS) is used to enumerate the entries. The DWDS index is the list
 * intersected with the DWDS dictionary: every entry it carries IS on the list, so
 * a promotion taken from it can never add an entry the list does not have — the
 * index can only be incomplete, never wrong in that direction. The partial
 * harvest (letters A–N) is recorded in the file header.
 *
 * Every line is verified against the corpus, not trusted:
 *   authored  — the entry is an item of some A0/A1/A2 word list  → drop
 *   met       — the learner meets it in a lesson, a step or a reading text → keep
 * Anything neither met nor authored is printed and dropped: the measure can only
 * move on entries the corpus really carries.
 *
 *     GOETHE_A2_HARVEST=/path/to/harvest.txt node tools/goethe-a2-candidates.js [--write]
 */
const fs = require('fs');
const path = require('path');
const { loadCorpus, buildBands, makeClassify } = require('./goethe-match');

const root = path.resolve(__dirname, '..');
/* LEVEL selects which band the entries are measured against and where the
   defaults point: A2 (default) or B1. The A2 behaviour is unchanged. */
const LEVEL = (process.env.GOETHE_LEVEL || 'A2').toUpperCase();
const LEVELS = LEVEL === 'B1' ? ['A0', 'A1', 'A2', 'B1'] : ['A0', 'A1', 'A2'];
const HARVEST = process.env.GOETHE_HARVEST ||
  (LEVEL === 'B1' ? '/home/user/goethe/b1_headwords.txt'
    : process.env.GOETHE_A2_HARVEST || '/home/user/goethe/a2_harvest_an.txt');
const OUT = path.join(root, 'tools', 'goethe-' + LEVEL.toLowerCase() + '-candidates.txt');
const WRITE = process.argv.includes('--write');

/* The harvest file is kept outside the repository (the list is copyrighted), so a
   sandbox without it falls back to the recorded gap file: the gap's open entries
   ARE the un-authored set, and the lines marked `met` in it are exactly the pool
   this tool builds. The fallback is exact for those entries and is printed as
   such; --gap forces it. */
const GAP = path.join(root, 'tools', 'goethe-' + LEVEL.toLowerCase() + '-gap.txt');
let SOURCE = HARVEST, FROM_GAP = false;
if (!fs.existsSync(HARVEST) && fs.existsSync(GAP)) { SOURCE = GAP; FROM_GAP = true; }
if (!fs.existsSync(SOURCE)) {
  console.error('missing harvest file: ' + HARVEST + ' (and no gap file at ' + GAP + ')');
  console.error('It is kept outside the repository (the list is copyrighted). See the tool header.');
  process.exit(2);
}
const win = loadCorpus(root);
const { bands, materialText } = buildBands(win, { cumulative: LEVELS });
const classify = makeClassify(bands.cumulative, materialText);

const lines = fs.readFileSync(SOURCE, 'utf8').split('\n')
  .map(l => l.replace(/^#.*$/, '').trim()).filter(Boolean)
  .map(l => (FROM_GAP ? l.replace(/^(met|new)\s+/, '') : l));

const authored = [], candidates = [], neither = [];
lines.forEach(entry => {
  const c = classify(entry);
  if (c.inHead) authored.push(entry);
  else if (c.met) candidates.push(entry);
  else neither.push(entry);
});

console.log('\nGoethe ' + LEVEL + ' harvest (verified against the corpus, not trusted)');
console.log('  source                ' + (FROM_GAP ? 'gap file (the open set) — no external transcription needed'
  : SOURCE));
console.log('  lines read            ' + lines.length);
console.log('  already authored      ' + authored.length + '  → dropped');
console.log('  MET, NOT AUTHORED     ' + candidates.length + '  → the promotion pool');
console.log('  neither met nor named ' + neither.length + '  → dropped (the corpus does not carry them)');
if (authored.length) console.log('  authored: ' + authored.slice(0, 12).join(' · ') + (authored.length > 12 ? ' …' : ''));
if (neither.length) console.log('  not carried: ' + neither.slice(0, 12).join(' · ') + (neither.length > 12 ? ' … (' + neither.length + ' in all)' : ''));

if (WRITE) {
  const head = '# Candidate pool: Goethe ' + LEVEL + ' entries the learner MET in material and no word list names.\n' +
    (FROM_GAP
      ? '# Generated by tools/goethe-a2-candidates.js from the recorded gap file of this level\n' +
        '# (tools/goethe-' + LEVEL.toLowerCase() + '-gap.txt), whose open entries ARE the un-authored set;\n' +
        '# the lines marked met there are this pool. The gap file itself came from the full list read\n' +
        '# whole, so no line here can be off the list.\n'
      : '# Generated by tools/goethe-a2-candidates.js from the DWDS index of the same Goethe ' + LEVEL + '\n' +
        '# list (the list\u2019s machine-readable twin, kept outside the repository because the list is\n' +
        '# copyrighted). The whole index was read, so no line can be missing.\n') +
    '# Every line was verified against the corpus: authored lines and lines the corpus does not\n' +
    '# carry are excluded. Promoting an entry means naming it in a word list; the matcher then\n' +
    '# verifies authored AND met before the entry counts, so this file can never overstate.\n';
  fs.writeFileSync(OUT, head + candidates.join('\n') + '\n');
  console.log('  wrote ' + path.relative(root, OUT) + ' (' + candidates.length + ' candidates)');
}
process.exit(0);
